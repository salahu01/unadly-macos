#!/bin/bash
# Refreshes Resources/adhosts.txt from anudeepND/blacklist (MIT licence, see CREDITS.md).
# Only lists whose licence allows redistribution belong here.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="https://raw.githubusercontent.com/anudeepND/blacklist/master/adservers.txt"
OUT="$ROOT/Resources/adhosts.txt"

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
curl -fsSL "$SRC" -o "$TMP"

{
  echo "# Ad servers blocked by Unadly. Source: https://github.com/anudeepND/blacklist (MIT)."
  echo "# Generated by tools/update-blocklist.sh on $(date -u +%Y-%m-%d). Do not edit by hand."
  grep -v '^\s*#' "$TMP" | awk 'NF {print tolower($NF)}' | grep -E '^[a-z0-9_-]+(\.[a-z0-9_-]+)+$' \
    | grep -vxE '0\.0\.0\.0|127\.0\.0\.1' | sort -u
} > "$OUT"
echo "==> $(grep -vc '^#' "$OUT") hosts written to Resources/adhosts.txt"
